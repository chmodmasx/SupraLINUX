#!/usr/bin/env python3
"""Regenerate the SupraLINUX APT pin from the local package controls.

The old Package: * pin also covered packages that SupraLINUX does not rebuild
and could hide Ubuntu updates. Keep the pin limited to the binary packages that
this repository actually ships.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "installer" / "apt" / "90-supralinux.pref"
PER_LINE = 12
EXCLUDE = {"supralinux-build-test"}


def package_names() -> list[str]:
    names: set[str] = set()
    for control in (ROOT / "packages").rglob("debian/control"):
        for line in control.read_text(errors="ignore").splitlines():
            if line.startswith("Package:"):
                name = line.split(":", 1)[1].strip()
                if name and not name.startswith("${") and name not in EXCLUDE:
                    names.add(name)
    return sorted(names)


def preference_text(names):
    lines = [
        "# Generated by tools/update-apt-pref.py from packages/**/debian/control.",
        "# Only packages rebuilt by SupraLINUX are pinned; Ubuntu keeps its updates.",
        "",
    ]
    for start in range(0, len(names), PER_LINE):
        lines.append("Package: " + " ".join(names[start : start + PER_LINE]))
        lines.append("Pin: release o=SupraLINUX")
        lines.append("Pin-Priority: 1001")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the generated pin is not up to date")
    args = parser.parse_args()
    names = package_names()
    text = preference_text(names)
    if args.check:
        if not OUT.is_file() or OUT.read_text() != text:
            raise SystemExit(f"{OUT}: generated pin is out of date")
        print(f"{OUT}: {len(names)} packages, pin is current")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"{OUT}: {len(names)} packages, {(len(names) + PER_LINE - 1) // PER_LINE} stanzas")


if __name__ == "__main__":
    main()
